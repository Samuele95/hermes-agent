"""Render the Android app's Kotlin protocol types from the published OpenRPC contract.

The app speaks tui_gateway JSON-RPC to the core it embeds. This renders the part of
``apps/shared/src/gateway-contract.openrpc.json`` the app uses (:data:`SURFACE`) into kotlinx
serialization types plus typed method / event / server-request descriptors. Like
``scripts/gen_gateway_contracts.py`` it models a small JSON-Schema subset — object/properties/
required, primitives, enum, anyOf-with-null, array/items, typed maps, ``$ref`` — and raises on
anything else, so an unmodelled shape is a generation error rather than a silent wrong decode.
Untyped fields and multi-type unions stay raw JSON (``JsonElement``).

The core ships in the APK at the same commit as this client, so the two never drift on a device.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "apps" / "shared" / "src" / "gateway-contract.openrpc.json"
PACKAGE = "com.nousresearch.hermes.bridge.protocol"
OUT = ROOT / "apps" / "android" / "bridge" / "src" / "main" / "java" / Path(*PACKAGE.split(".")) / "Protocol.kt"


@dataclass(frozen=True)
class Surface:
    methods: tuple[str, ...]
    events: tuple[str, ...]
    requests: tuple[str, ...]


SURFACE = Surface(
    methods=("client.capabilities", "config.get", "config.set", "gateway.capabilities", "model.disconnect",
             "model.options", "ping", "prompt.submit", "request.answer", "session.create", "session.history", "session.interrupt",
             "session.list", "session.resume", "session.save", "setup.status"),
    events=("approval.cancelled", "error", "message.complete", "message.delta", "message.interim", "message.start",
            "reasoning.available", "reasoning.delta", "session.info", "session.title", "session.usage",
            "request.cancel", "status.update", "thinking.delta", "tool.complete", "tool.generating", "tool.start"),
    requests=("approval", "clarify", "secret"),
)

HEADER = """\
// GENERATED by scripts/android/gen_kotlin_client.py from apps/shared/src/gateway-contract.openrpc.json — DO NOT EDIT.
// Regenerate: python -m scripts.android.gen_kotlin_client
// tests/scripts/test_android_kotlin_client.py fails when this file is stale.
"""

PRELUDE = """
package {package}

import kotlinx.serialization.KSerializer
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/** A client→core method: its wire name and the serializers of its params and result. */
class Method<P, R>(val name: String, val params: KSerializer<P>, val result: KSerializer<R>)

/** A core→client `event` frame type and the serializer of its payload. */
class Event<P>(val name: String, val payload: KSerializer<P>)

/** A core→client request (an in-turn prompt) and the serializers of its params and the answer. */
class Request<P, R>(val name: String, val params: KSerializer<P>, val result: KSerializer<R>)
"""

_KEYWORDS = frozenset("as break class continue do else false for fun if in interface is null object package return "
                      "super this throw true try typealias typeof val var when while".split())
_PRIMITIVES = {"string": "String", "integer": "Long", "number": "Double", "boolean": "Boolean"}


def _camel(name: str) -> str:
    head, *rest = re.sub(r"\W", "_", name).split("_")
    ident = head + "".join(part[:1].upper() + part[1:] for part in rest)
    ident = ident if ident and not ident[0].isdigit() else f"_{ident}"
    return f"`{ident}`" if ident in _KEYWORDS else ident


def _constant(name: str) -> str:
    ident = re.sub(r"\W", "_", re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)).upper() or "EMPTY"
    return ident if not ident[0].isdigit() else f"_{ident}"


def _kotlin_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False).replace("$", "\\$")


def _doc(text: str | None) -> str:
    line = (text or "").strip().splitlines()[0].strip() if (text or "").strip() else ""
    return f"/** {line.replace('*/', '* /')} */\n" if line else ""


class _Renderer:
    def __init__(self, schemas: dict[str, dict]):
        self.schemas = schemas
        self.needed: dict[str, None] = {}

    def top(self, schema: dict, where: str) -> str:
        """The class behind a method's params/result or an event's payload: a named schema, or a raw
        object for one declared inline without fields (``message.start`` has no payload)."""
        if "$ref" in schema:
            return self.ref(schema)
        if self.type_of(schema, where) == ("JsonObject", False):
            return "JsonObject"
        raise ValueError(f"{where}: an inline top-level schema must be a field-less object")

    def ref(self, schema: dict) -> str:
        name = schema["$ref"].rsplit("/", 1)[-1]
        if name not in self.schemas:
            raise ValueError(f"unresolved $ref {schema['$ref']}")
        if name not in self.needed:
            self.needed[name] = None
            self.declare(name)  # walk eagerly so every reachable schema is collected
        return name

    def type_of(self, schema: dict, where: str) -> tuple[str, bool]:
        """(Kotlin type, nullable) of one property schema."""
        for unsupported in ("oneOf", "allOf", "not"):
            if unsupported in schema:
                raise ValueError(f"{where}: {unsupported} is not modelled")
        if "$ref" in schema:
            return self.ref(schema), False
        if "anyOf" in schema:
            others = [alt for alt in schema["anyOf"] if alt.get("type") != "null"]
            nullable = len(others) < len(schema["anyOf"])
            if len(others) == 1:
                kind, inner_nullable = self.type_of(others[0], where)
                return kind, nullable or inner_nullable
            return "JsonElement", nullable
        kind = schema.get("type")
        if kind in _PRIMITIVES:
            return _PRIMITIVES[kind], False
        if kind == "array":
            if "items" not in schema:
                return "List<JsonElement>", False
            item, item_nullable = self.type_of(schema["items"], where)
            return f"List<{item}{'?' if item_nullable else ''}>", False
        if kind == "object":
            if schema.get("properties"):
                raise ValueError(f"{where}: an inline object with properties needs a named schema")
            values = schema.get("additionalProperties")
            if isinstance(values, dict):
                value, value_nullable = self.type_of(values, where)
                return f"Map<String, {value}{'?' if value_nullable else ''}>", False
            return "JsonObject", False
        if kind == "null":
            return "JsonElement", True
        if kind is None:
            return "JsonElement", False
        raise ValueError(f"{where}: type {kind!r} is not modelled")

    def default(self, value: object, kind: str, where: str) -> str:
        if value is None:
            return "null"
        if kind == "JsonElement" and isinstance(value, (str, bool, int, float)):
            return f"JsonPrimitive({_kotlin_string(value) if isinstance(value, str) else json.dumps(value)})"
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, (int, float)) and kind in ("Long", "Double"):
            return f"{float(value)!r}" if kind == "Double" else str(int(value))
        if isinstance(value, str) and kind == "String":
            return _kotlin_string(value)
        if isinstance(value, str) and kind in self.schemas and "enum" in self.schemas[kind]:
            return f"{kind}.{_constant(value)}"
        if value == [] and kind.startswith("List<"):
            return "emptyList()"
        if value == {} and kind.startswith("Map<"):
            return "emptyMap()"
        if value == {} and kind == "JsonObject":
            return "JsonObject(emptyMap())"
        raise ValueError(f"{where}: default {value!r} for {kind} is not modelled")

    def declare(self, name: str) -> None:
        schema = self.schemas[name]
        if schema.get("type") == "object":
            for key, prop in schema.get("properties", {}).items():
                self.type_of(prop, f"{name}.{key}")
        elif not (schema.get("type") == "string" and "enum" in schema):
            raise ValueError(f"{name}: only object and string-enum schemas are modelled")

    def render(self, name: str) -> str:
        schema = self.schemas[name]
        doc = _doc(schema.get("description"))
        if "enum" in schema:
            entries = "".join(f"    @SerialName({_kotlin_string(v)}) {_constant(v)},\n" for v in schema["enum"])
            return f"{doc}@Serializable\nenum class {name} {{\n{entries}}}\n"
        properties = schema.get("properties", {})
        if not properties:
            return f"{doc}@Serializable\ndata object {name}\n"
        required = set(schema.get("required", ()))
        fields = []
        for key, prop in properties.items():
            kind, nullable = self.type_of(prop, f"{name}.{key}")
            line = f"    @SerialName({_kotlin_string(key)}) val {_camel(key)}: {kind}"
            if key in required:
                fields.append(f"{line}{'?' if nullable else ''},\n")
                continue
            value = prop.get("default")
            nullable = nullable or value is None
            fields.append(f"{line}{'?' if nullable else ''} = {self.default(value, kind, f'{name}.{key}')},\n")
        return f"{doc}@Serializable\ndata class {name}(\n{''.join(fields)})\n"


def _schema_of(entry: dict | None, where: str) -> dict:
    if entry is None:
        raise ValueError(f"{where}: missing schema")
    return entry["schema"]


def render(contract: dict, surface: Surface = SURFACE) -> str:
    r = _Renderer(contract["components"]["schemas"])
    by_name = {kind: {entry["name"]: entry for entry in contract[key]}
               for kind, key in (("method", "methods"), ("event", "x-notifications"), ("request", "x-server-requests"))}

    def pick(kind: str, name: str) -> dict:
        if name not in by_name[kind]:
            raise ValueError(f"{kind} {name} is not in the contract")
        return by_name[kind][name]

    out = [HEADER, PRELUDE.format(package=PACKAGE)]
    for title, kind, names in (("Methods", "method", surface.methods), ("Requests", "request", surface.requests)):
        out.append(f"\nobject {title} {{\n")
        cls = "Method" if kind == "method" else "Request"
        for name in names:
            entry = pick(kind, name)
            params = r.top(_schema_of(entry["params"][0] if entry.get("params") else None, name), name)
            result = r.top(_schema_of(entry.get("result"), name), name)
            out.append(f"    val {_constant(name)} = {cls}({_kotlin_string(name)}, {params}.serializer(), "
                       f"{result}.serializer())\n")
        out.append("}\n")
    out.append("\nobject Events {\n")
    for name in surface.events:
        params = pick("event", name).get("params") or []
        payload = f"{r.top(params[0]['schema'], name) if params else 'JsonObject'}.serializer()"
        out.append(f"    val {_constant(name)} = Event({_kotlin_string(name)}, {payload})\n")
    out.append("}\n")
    out.extend(f"\n{r.render(name)}" for name in sorted(r.needed))
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    text = render(json.loads(CONTRACT.read_text(encoding="utf-8-sig")))
    current = OUT.read_text(encoding="utf-8-sig") if OUT.exists() else None
    if current == text:
        return 0
    if "--check" in (argv if argv is not None else sys.argv[1:]):
        print(f"stale: {OUT.relative_to(ROOT)} — run python -m scripts.android.gen_kotlin_client", file=sys.stderr)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
